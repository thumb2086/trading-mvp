export const SECTORS = Array.from(new Set(COMMON_STOCKS.map(s => s.sector))).filter(Boolean)

let cachedAllStocks: StockInfo[] | null = null
let lastFetch = 0

export async function getAllTWSEStocks(): Promise<StockInfo[]> {
  if (cachedAllStocks && Date.now() - lastFetch < 3600000) return cachedAllStocks
  try {
    const res = await fetch("https://openapi.twse.com.tw/v1/exchangeReport/STOCK_DAY_ALL", {
      headers: { "User-Agent": "Mozilla/5.0" },
    })
    const data = await res.json()
    if (!Array.isArray(data)) throw new Error("Invalid")
    const nameMap = new Map(COMMON_STOCKS.filter(s => s.name).map(s => [s.symbol, s.name]))
    cachedAllStocks = data
      .map((s: any) => ({ symbol: String(s.Code).padStart(4, "0"), name: nameMap.get(String(s.Code).padStart(4, "0")) || s.Name || "", sector: "" }))
      .filter((s: StockInfo) => s.symbol && /^\d{4}$/.test(s.symbol) && s.name)
    lastFetch = Date.now()
    return cachedAllStocks
  } catch { return COMMON_STOCKS }
}

export async function searchStocks(query: string, sector?: string): Promise<StockInfo[]> {
  if (!query && !sector) return COMMON_STOCKS
  const all = await getAllTWSEStocks()
  const q = query.toLowerCase()
  let filtered = all
  if (q) filtered = filtered.filter(s => s.symbol.includes(q) || s.name.toLowerCase().includes(q))
  return filtered.slice(0, 100)
}
